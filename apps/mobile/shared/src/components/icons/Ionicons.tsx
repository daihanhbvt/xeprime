type IoniconsProps = ComponentProps<typeof ExpoIonicons>;

export function Ionicons(props: IoniconsProps) {
  const { name, size = 24, color, style } = props;
  const tint = typeof color === 'string' ? color : 'currentColor';
  // Xe máy: AntD không có glyph - dùng CÙNG nét `MotorbikeOutlined` tự vẽ của web.
  if (name === 'bicycle' || name === 'bicycle-outline') {
    return (
      <View style={style as never} pointerEvents="none">
        <MotorbikeIcon size={size} color={tint} />
      </View>
    );
  }
  const ant = IONICON_TO_ANT[name as keyof typeof ExpoIonicons.glyphMap];
  if (!ant) return <ExpoIonicons {...props} />;
  return (
    <View style={style as never} pointerEvents="none">
      <AntIcon icon={ant} size={size} color={tint} />
    </View>
  );
}

